package store

import (
	"context"
	"time"
)

// TokenGroup is a group of tokens of an org. It is not the OCPI group of a token
// (Token.GroupId), which the issuer of the token sets: the org makes these groups itself,
// to charge their tokens with another tariff.
type TokenGroup struct {
	Id    string // UUIDv7, generated by the store when empty
	OrgId string
	Name  string // unique in the org
	// PrefixMatch makes the UIDs of the tokens of the group prefixes: a presented UID that
	// starts with one of them, in any case, belongs to the group.
	PrefixMatch bool
	// OverrideTariffRef is the id of the tariff that the tokens of the group are charged
	// with, whatever the tariff of the connector; nil when the group has none.
	OverrideTariffRef *string
	CreatedAt         time.Time
	UpdatedAt         time.Time
}

// TokenGroupStore holds the token groups of the orgs and which tokens are in them. A
// token is in one group at most (Token.TokenGroupId), and a group only has tokens of its
// own org.
//
// Lookups return nil, nil when there is no such record; an id that is not a UUID names
// no record. A create that would repeat a unique key returns an error wrapping
// ErrAlreadyExists, and a write that refers to a tariff that does not exist one wrapping
// ErrNotFound; a deleted tariff still exists. The store does not check that the tariff
// belongs to the org of the group: the caller does.
type TokenGroupStore interface {
	// CreateTokenGroup stores the group and fills in what the store sets: the Id (when
	// empty) and the timestamps. It returns ErrAlreadyExists when the org already has a
	// group with the name.
	CreateTokenGroup(ctx context.Context, g *TokenGroup) error
	// UpdateTokenGroup writes Name, PrefixMatch and OverrideTariffRef of the group g.Id,
	// and the stored group back into g. A group that does not exist is ErrNotFound, a
	// name that another group of the org has ErrAlreadyExists.
	UpdateTokenGroup(ctx context.Context, g *TokenGroup) error
	LookupTokenGroup(ctx context.Context, groupId string) (*TokenGroup, error)
	// ListTokenGroups returns a page of the groups of the orgs ordered by id, and the
	// cursor of the next page ("" after the last page). No org lists nothing.
	ListTokenGroups(ctx context.Context, orgIds []string, page PageRequest) ([]*TokenGroup, string, error)
	// DeleteTokenGroup deletes the group; its tokens are in no group afterwards.
	// Deleting a group that does not exist does nothing.
	DeleteTokenGroup(ctx context.Context, groupId string) error
	// SetTokenGroup puts the tokens of the org with the UID (the token of every party of
	// the org that has the UID) into the group, out of the group that they were in; a nil
	// groupId takes them out of their group. It returns ErrNotFound when the org has no
	// token with the UID, and when the group does not exist or belongs to another org.
	SetTokenGroup(ctx context.Context, orgId, tokenUid string, groupId *string) error
	// ListTokenGroupMembers returns a page of the tokens of the group, the token that was
	// stored first first, and the cursor of the next page ("" after the last page).
	ListTokenGroupMembers(ctx context.Context, groupId string, page PageRequest) ([]*Token, string, error)
	// FindTokenGroupForUid returns the group that a presented token UID belongs to in the
	// org: the group of the token of the org with exactly this UID, when it is in one.
	// Otherwise the group with PrefixMatch that has the token with the longest UID that
	// the presented UID starts with, ignoring case (of two such tokens the one whose UID
	// sorts first). It returns nil when there is no such group.
	FindTokenGroupForUid(ctx context.Context, orgId, uid string) (*TokenGroup, error)
}
