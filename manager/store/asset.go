package store

import (
	"context"
	"time"
)

// AssetEvseStatus is the lifecycle status of an EVSE in the asset model. The live status
// of an active EVSE comes from the StatusStore.
type AssetEvseStatus string

const (
	AssetEvseStatusActive  AssetEvseStatus = "ACTIVE"
	AssetEvseStatusPlanned AssetEvseStatus = "PLANNED"
	AssetEvseStatusRemoved AssetEvseStatus = "REMOVED"
)

// RegularHours is one opening period of a weekday (OCPI RegularHours).
type RegularHours struct {
	Weekday     int    `json:"weekday"`      // 1 = Monday ... 7 = Sunday (OCPI)
	PeriodBegin string `json:"period_begin"` // "HH:MM", local time of the location
	PeriodEnd   string `json:"period_end"`
}

// ExceptionalPeriod is a period in which a location is open or closed against its
// regular hours (OCPI ExceptionalPeriod).
type ExceptionalPeriod struct {
	PeriodBegin time.Time `json:"period_begin"`
	PeriodEnd   time.Time `json:"period_end"`
}

// OpeningTimes are the opening times of a location (OCPI Hours).
type OpeningTimes struct {
	TwentyFourSeven     bool                `json:"twentyfourseven"`
	RegularHours        []RegularHours      `json:"regular_hours,omitempty"`
	ExceptionalOpenings []ExceptionalPeriod `json:"exceptional_openings,omitempty"`
	ExceptionalClosings []ExceptionalPeriod `json:"exceptional_closings,omitempty"`
}

// AssetLocation is a location of an org, published through OCPI by one of the org's
// parties. Lists of a location (Facilities, ExternalRefs) are read back as empty slices,
// never nil.
type AssetLocation struct {
	Id                 string // UUIDv7, generated by the store when empty
	OrgId              string
	PartyRef           string // id of a party of the tenant (Tenant.Parties[].Id)
	OcpiId             string // OCPI location id (CiString(36)); the store sets it to Id when empty
	Name               *string
	Address            string
	City               string
	PostalCode         *string
	State              *string
	Country            string // ISO 3166-1 alpha-3 (OCPI)
	Latitude           string // OCPI decimal string, e.g. "51.047599"
	Longitude          string
	TimeZone           string // IANA, e.g. "Europe/Madrid"
	ParkingType        *string
	Publish            bool
	OpeningTimes       *OpeningTimes
	Facilities         []string
	ChargingWhenClosed *bool
	ExternalRefs       []string // at most 3 references in other systems
	Version            int64    // optimistic concurrency, starts at 1
	CreatedAt          time.Time
	UpdatedAt          time.Time
}

// AssetEvse is an EVSE of a charge station at a location. For OCPP 1.6 every connector
// of the station is an EVSE of its own.
type AssetEvse struct {
	Id                string // UUIDv7, generated by the store when empty; also the OCPI EVSE uid
	OrgId             string
	LocationId        string
	StationKey        string  // charge_station_id ({org_key}.{stationId})
	OcppEvseId        int     // 2.0.1 EVSE id; for 1.6 the 1.6 connectorId
	EvseId            *string // eMI3, e.g. "ES*CCM*E12345*1"
	PhysicalReference *string
	Status            AssetEvseStatus // ACTIVE when empty on create
	// Connectors are the connectors of the EVSE, ordered by OcppConnectorId. Every read
	// of an EVSE fills them (an empty slice when there are none); CreateAssetEvse creates
	// them with the EVSE, UpdateAssetEvse ignores them.
	Connectors []*AssetConnector
	Version    int64
	CreatedAt  time.Time
	UpdatedAt  time.Time
}

// AssetConnector is a connector of an EVSE.
type AssetConnector struct {
	Id               string // UUIDv7, generated by the store when empty
	OrgId            string // the org of the EVSE: the store sets it from the EVSE on create
	EvseUid          string // AssetEvse.Id (not the eMI3 EvseId)
	OcppConnectorId  int    // 2.0.1 connector id within the EVSE; always 1 for 1.6
	OcpiId           string // OCPI connector id within the EVSE; the store sets it to strconv.Itoa(OcppConnectorId) when empty
	Standard         string // OCPI ConnectorType, e.g. IEC_62196_T2, IEC_62196_T2_COMBO, CHADEMO
	Format           string // SOCKET | CABLE
	PowerType        string // AC_1_PHASE | AC_2_PHASE | AC_2_PHASE_SPLIT | AC_3_PHASE | DC
	MaxVoltage       int32
	MaxAmperage      int32
	MaxElectricPower *int32  // W
	TariffRef        *string // id of a tariff
	AdhocTariffRef   *string // id of an AD_HOC_PAYMENT tariff
	Version          int64
	CreatedAt        time.Time
	UpdatedAt        time.Time
}

// AssetLocationFilter selects the locations that ListAssetLocations returns.
type AssetLocationFilter struct {
	// OrgIds are the orgs whose locations are listed (the principal's org, or its
	// subtree, resolved by the caller). No org lists nothing.
	OrgIds   []string
	PartyRef *string
	Publish  *bool
	Query    *string // case-insensitive substring of name, address, city or OCPI id
	Page     PageRequest
}

// AssetStore holds the native asset model: locations, the EVSEs of the charge stations
// at a location and the connectors of an EVSE.
//
// Creates fill in what the store sets (Id when empty, defaults, Version 1, CreatedAt,
// UpdatedAt) in the record they are given; updates write the new Version and UpdatedAt
// back. An update applies only when the record still has the Version that it carries:
// otherwise it returns an error wrapping ErrVersionConflict, and one wrapping ErrNotFound
// when the record does not exist. A create that would repeat a unique key returns an
// error wrapping ErrAlreadyExists, and one wrapping ErrNotFound when a record that it
// refers to (location, charge station, EVSE) does not exist.
//
// Lookups return nil, nil when there is no such record; an id that is not a UUID names
// no record. Deletes of a record that does not exist do nothing.
type AssetStore interface {
	// CreateAssetLocation returns ErrAlreadyExists when the party already has a location
	// with the OCPI id.
	CreateAssetLocation(ctx context.Context, loc *AssetLocation) error
	// UpdateAssetLocation writes every field but Id, OrgId and CreatedAt.
	UpdateAssetLocation(ctx context.Context, loc *AssetLocation) error
	LookupAssetLocation(ctx context.Context, locationId string) (*AssetLocation, error)
	LookupAssetLocationByOcpiId(ctx context.Context, partyRef, ocpiId string) (*AssetLocation, error)
	// ListAssetLocations returns a page ordered by id and the cursor of the next page
	// ("" after the last page).
	ListAssetLocations(ctx context.Context, filter AssetLocationFilter) ([]*AssetLocation, string, error)
	// DeleteAssetLocation returns ErrInUse while EVSEs are at the location.
	DeleteAssetLocation(ctx context.Context, locationId string) error

	// CreateAssetEvse creates the EVSE and its connectors in one transaction; it returns
	// ErrAlreadyExists when the station already has an EVSE with the OCPP EVSE id, or
	// another EVSE has the eMI3 id.
	CreateAssetEvse(ctx context.Context, evse *AssetEvse) error
	// UpdateAssetEvse writes the EVSE fields but Id, OrgId and CreatedAt; it does not
	// touch the connectors.
	UpdateAssetEvse(ctx context.Context, evse *AssetEvse) error
	LookupAssetEvse(ctx context.Context, evseUid string) (*AssetEvse, error)
	LookupAssetEvseByOcpp(ctx context.Context, stationKey string, ocppEvseId int) (*AssetEvse, error)
	// ListAssetEvsesForLocation orders the EVSEs by OCPP EVSE id, then station key.
	ListAssetEvsesForLocation(ctx context.Context, locationId string) ([]*AssetEvse, error)
	// ListAssetEvsesForStation orders the EVSEs by OCPP EVSE id.
	ListAssetEvsesForStation(ctx context.Context, stationKey string) ([]*AssetEvse, error)
	// DeleteAssetEvse deletes the EVSE and its connectors.
	DeleteAssetEvse(ctx context.Context, evseUid string) error

	CreateAssetConnector(ctx context.Context, c *AssetConnector) error
	// UpdateAssetConnector writes every field but Id, OrgId, EvseUid and CreatedAt.
	UpdateAssetConnector(ctx context.Context, c *AssetConnector) error
	LookupAssetConnector(ctx context.Context, connectorUid string) (*AssetConnector, error)
	LookupAssetConnectorByOcpp(ctx context.Context, stationKey string, ocppEvseId, ocppConnectorId int) (*AssetConnector, error)
	DeleteAssetConnector(ctx context.Context, connectorUid string) error

	// MoveChargeStationToLocation sets the location of the charge station and moves every
	// EVSE of the station that is elsewhere to the location (a new Version each), all
	// together. A station or a location that does not exist is ErrNotFound. The caller
	// checks that the location belongs to the org of the station.
	MoveChargeStationToLocation(ctx context.Context, stationKey, locationId string) error
	// DecommissionChargeStation moves the charge station to the state decommissioned, with
	// the reason (nil clears it), and sets every EVSE of the station that is not REMOVED
	// to REMOVED (a new Version each), all together. A station that does not exist is
	// ErrNotFound.
	DecommissionChargeStation(ctx context.Context, stationKey string, reason *string) error
	// TransferChargeStation moves a charge station to another org, all together: the
	// station, every EVSE of the station and their connectors (a new Version each), its
	// charging profiles and, with MoveLocation, its location. The connectors lose their
	// tariffs, which belong to the old org. Transactions, meter values and the other
	// history of the station keep their org, and the station key does not change.
	//
	// A station that does not exist is ErrNotFound; one that is decommissioned or whose
	// org is not FromOrgId is ErrInvalidState. MoveLocation with a station without a
	// location, or with a location where another station or an EVSE of another station
	// is, is ErrInvalidState; a party of the target that already has a location with the
	// OCPI id of the location is ErrAlreadyExists. A TargetLocationId that does not exist
	// is ErrNotFound; without one, a station with EVSEs is ErrInvalidState. The caller
	// checks that the target location belongs to ToOrgId. Nothing is written when it
	// fails.
	TransferChargeStation(ctx context.Context, p TransferParams) (*TransferResult, error)
}

// TransferParams says where TransferChargeStation moves a charge station.
type TransferParams struct {
	StationKey string
	// FromOrgId is the org that the station belongs to, as stored.
	FromOrgId string
	ToOrgId   string
	// MoveLocation moves the location of the station, which only the station uses, to
	// ToOrgId with the party TargetPartyRef; the EVSEs of the station go there.
	MoveLocation   bool
	TargetPartyRef *string // required with MoveLocation: a party of ToOrgId
	// TargetLocationId is the location of ToOrgId where the station and its EVSEs go when
	// the location does not move. Nil leaves a station without EVSEs without a location.
	TargetLocationId *string
}

// TransferResult says what TransferChargeStation moved.
type TransferResult struct {
	StationKey string
	// LocationId is the location of the station and its EVSEs now; nil when it has none.
	LocationId      *string
	LocationMoved   bool
	EvsesMoved      int
	ConnectorsMoved int
	// ClearedTariffRefs are the tariffs (of the old org) that the moved connectors
	// referred to, each once, sorted.
	ClearedTariffRefs []string
}
