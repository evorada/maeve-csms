-- 1. Enriched columns
-- meter_start and meter_stop hold a lifetime energy register in Wh, which does not fit in
-- an INT for a busy DC charger. meter_start becomes nullable: NULL means not known.
ALTER TABLE transactions
    ALTER COLUMN meter_start TYPE BIGINT,
    ALTER COLUMN meter_start DROP NOT NULL,
    ALTER COLUMN meter_stop TYPE BIGINT,
    ADD COLUMN IF NOT EXISTS evse_id INT,
    ADD COLUMN IF NOT EXISTS connector_id INT,
    ADD COLUMN IF NOT EXISTS energy_wh BIGINT,
    ADD COLUMN IF NOT EXISTS id_token_group VARCHAR(36),
    ADD COLUMN IF NOT EXISTS reservation_id INT;

-- 2. Per-station transaction identity
-- Transaction ids are only unique per charge station (OCPP 2.0.1 ids are generated by the
-- station), so the primary key becomes (charge_station_id, id) and the meter values are
-- keyed the same way.
ALTER TABLE transaction_meter_values ADD COLUMN IF NOT EXISTS charge_station_id VARCHAR(48);
UPDATE transaction_meter_values mv
    SET charge_station_id = t.charge_station_id
    FROM transactions t
    WHERE t.id = mv.transaction_id AND mv.charge_station_id IS NULL;
ALTER TABLE transaction_meter_values ALTER COLUMN charge_station_id SET NOT NULL;
ALTER TABLE transaction_meter_values DROP CONSTRAINT IF EXISTS transaction_meter_values_transaction_id_fkey;
ALTER TABLE transactions DROP CONSTRAINT IF EXISTS transactions_pkey;
ALTER TABLE transactions ADD CONSTRAINT transactions_pkey PRIMARY KEY (charge_station_id, id);
ALTER TABLE transaction_meter_values
    ADD CONSTRAINT transaction_meter_values_transaction_fkey
    FOREIGN KEY (charge_station_id, transaction_id)
    REFERENCES transactions (charge_station_id, id)
    ON DELETE CASCADE ON UPDATE CASCADE;
DROP INDEX IF EXISTS idx_meter_values_transaction_id;
CREATE INDEX IF NOT EXISTS idx_transaction_meter_values_tx
    ON transaction_meter_values (charge_station_id, transaction_id, timestamp);
DROP INDEX IF EXISTS idx_transactions_station_id; -- covered by the new primary key

-- 3. Active transaction per connector, OCPP 1.6 transaction id allocator
CREATE INDEX IF NOT EXISTS idx_transactions_active_connector
    ON transactions (charge_station_id, connector_id)
    WHERE stop_timestamp IS NULL;
CREATE SEQUENCE IF NOT EXISTS ocpp16_transaction_id_seq
    AS INTEGER MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CYCLE;
